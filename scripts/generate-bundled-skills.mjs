#!/usr/bin/env node
// Generates src/generated/bundledSkills.ts by embedding the contents of every
// file under skills/*/ (including README.md — install-time logic filters it
// out, but the generated module keeps the same file set as disk so both
// stay diff-able). This lets `wfm skill list` / `wfm skill install` work
// from standalone `bun build --compile` binaries that don't ship skills/ on
// disk next to the executable.
//
// Output is deterministic (sorted skill names, sorted filenames) so re-running
// this script with no source changes produces zero diff.
//
// Run: bun run generate:skills
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skillsRoot = path.join(repoRoot, "skills");
const outFile = path.join(repoRoot, "src", "generated", "bundledSkills.ts");

function listSkillDirNames(root) {
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function listSkillFileNames(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort();
}

function renderSkillFiles(dir) {
  const fileNames = listSkillFileNames(dir);
  const entries = fileNames.map((fileName) => {
    const content = readFileSync(path.join(dir, fileName), "utf-8");
    return `    { name: ${JSON.stringify(fileName)}, content: ${JSON.stringify(content)} },`;
  });
  return `[\n${entries.join("\n")}\n  ]`;
}

const skillNames = listSkillDirNames(skillsRoot);

const skillEntries = skillNames.map((name) => {
  const dir = path.join(skillsRoot, name);
  return `  ${JSON.stringify(name)}: ${renderSkillFiles(dir)},`;
});

const output = `// AUTO-GENERATED by scripts/generate-bundled-skills.mjs — do not edit. Run: bun run generate:skills
export interface BundledSkillFile {
  name: string;
  content: string;
}

export const BUNDLED_SKILLS: Record<string, BundledSkillFile[]> = {
${skillEntries.join("\n")}
};
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, output, "utf-8");
console.log(`Wrote ${skillNames.length} bundled skill(s) to ${path.relative(repoRoot, outFile)}`);
